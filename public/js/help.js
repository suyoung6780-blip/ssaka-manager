function keyOf(path) {
  if (path === '/' || path === '') return '/';
  if (path.startsWith('/analysis')) return '/analysis';
  if (path.startsWith('/admin')) return '/admin';
  if (path.startsWith('/support')) return '/support';
  if (path.startsWith('/chat')) return '/chat';
  return Object.keys(HELP).filter((k) => k !== '/' && (path === k || path.startsWith(`${k}/`))).sort((a, b) => b.length - a.length)[0] || null;
}

export function showHelp(path) {
  const h = HELP[keyOf(path)];
  if (!h) return;
  const groups = [
    [isAdmin(), '운영자', h.admin],
    [isOwner(), '팀 대표', h.owner],
    [isCoach(), '지도자', h.coach],
    [!isCoach(), '선수', h.player],
    [true, '', h.all],
  ].filter(([on, , list]) => on && list?.length);
  modal(`<span class="eyebrow">HOW TO USE</span><h2>${h.title} 사용법</h2>
    <p class="muted">${h.intro}</p>
    ${groups.map(([, who, list]) => `${who ? `<h4 class="help-who">${who}</h4>` : ''}<ol class="guide-steps">${list.map((x) => `<li>${x}</li>`).join('')}</ol>`).join('')
      || '<p class="muted">이 화면은 지도자용이에요.</p>'}
    <p class="muted small">언제든 오른쪽 위 <b>❓ 사용법</b>으로 다시 볼 수 있어요.</p>`);
}

// 화면을 그린 뒤: '❓ 사용법' 버튼 달기 (자동으로 띄우지 않음 — 아직 안 눌러 본 페이지면 버튼에 작은 점)
let observer = null;
export function attachHelp(view, path) {
  observer?.disconnect();
  const key = keyOf(path);
  if (!key || !HELP[key] || !view) return;
  const seenKey = `ssaka.help.${state.user?.uid || ''}.${key}`;
  const seen = () => { try { return !!localStorage.getItem(seenKey); } catch { return true; } };
  const place = () => {
    if (view.querySelector('.help-btn')) return;
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = `btn ghost sm help-btn${seen() ? '' : ' new'}`;
    btn.textContent = '❓ 사용법';
    btn.onclick = () => {
      try { localStorage.setItem(seenKey, '1'); } catch { /* */ }
      btn.classList.remove('new');
      showHelp(path);
    };
    const spot = view.querySelector('.page-head .actions') || view.querySelector('.studio-top .st-actions');
    if (spot) spot.prepend(btn);
    else { const row = document.createElement('div'); row.className = 'help-row'; row.append(btn); view.prepend(row); }
  };
  place();
  // 필터 · 탭으로 화면을 다시 그려도 버튼이 남도록
  let queued = false;
  observer = new MutationObserver(() => { if (queued) return; queued = true; requestAnimationFrame(() => { queued = false; place(); }); });
  observer.observe(view, { childList: true });
}
